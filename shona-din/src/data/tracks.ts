export const trackById = Object.fromEntries(tracks.map((t) => [t.id, t])) as Record<
  string,
  Track
>

export function getTracksByIds(ids: string[]): Track[] {
  return ids.map((id) => trackById[id]).filter(Boolean)
}

export function findTracksByMemory(memoryId: string): Track[] {
  return tracks.filter((t) => t.memories.includes(memoryId))
}

export function findTracksByArtist(artistName: string): Track[] {
  return tracks.filter(
    (t) =>
      t.artist === artistName || t.featuredArtists?.includes(artistName),
  )
}

